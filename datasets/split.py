import os
import numpy as np
import pandas as pd
from iterstrat.ml_stratifiers import MultilabelStratifiedShuffleSplit

# Official split CSVs live in the simula/kvasir-capsule GitHub repo.
# If they're not on disk we download them once and cache them.
_OFFICIAL_SPLIT_URLS = {
    0: "https://raw.githubusercontent.com/simula/kvasir-capsule/master/official_splits/split_0.csv",
    1: "https://raw.githubusercontent.com/simula/kvasir-capsule/master/official_splits/split_1.csv",
}


def _ensure_official_split(split_dir, split_id, allow_download=True):
    os.makedirs(split_dir, exist_ok=True)
    dest = os.path.join(split_dir, f"split_{split_id}.csv")
    if not os.path.exists(dest):
        if not allow_download:
            raise FileNotFoundError(
                f"Split file missing: {dest}. For split_mode='official_clean', run "
                "datasets/make_clean_split.py first to generate the leakage-free splits."
            )
        import urllib.request
        url = _OFFICIAL_SPLIT_URLS[split_id]
        print(f"Downloading official split {split_id} from {url} ...")
        urllib.request.urlretrieve(url, dest)
        print(f"Saved to {dest}")
    return dest


def official_split(df, split_dir, split_id=0, val_frac=0.1, seed=42, allow_download=True):
    """
    Load a Kvasir-Capsule two-fold split (official or leakage-free clean).
    Each CSV lists filenames for one fold (format: filename,label).

    split_id=0: train=split_0.csv, test=split_1.csv
    split_id=1: train=split_1.csv, test=split_0.csv

    Val is carved as val_frac of train filenames (random, seeded).

    allow_download=False (used for the clean split) turns the missing-file
    auto-download off — the clean CSVs must be generated by make_clean_split.py.
    """
    train_id = split_id
    test_id  = 1 - split_id

    train_files = set(
        pd.read_csv(_ensure_official_split(split_dir, train_id, allow_download))["filename"]
        .dropna().tolist()
    )
    test_files = set(
        pd.read_csv(_ensure_official_split(split_dir, test_id, allow_download))["filename"]
        .dropna().tolist()
    )

    rng = np.random.RandomState(seed)
    train_list = sorted(train_files)
    rng.shuffle(train_list)
    n_val       = max(1, int(len(train_list) * val_frac))
    val_files   = set(train_list[:n_val])
    train_files = set(train_list[n_val:])

    return train_files, val_files, test_files


def stratified_video_split(df, video_col="video_id", class_col="finding_class",
                            train=0.8, val=0.1, seed=42):
    """
    Video-level stratified split. Each video is treated as one unit;
    splitting by frame would cause data leakage (adjacent frames).
    Uses iterative multi-label stratification so rare classes appear
    in all three splits even with few videos.
    Returns three sets of video IDs: train, val, test.
    """
    videos      = df.groupby(video_col)[class_col].apply(set).reset_index()
    all_classes = sorted(df[class_col].unique())

    presence = np.array([
        [1 if c in cls_set else 0 for c in all_classes]
        for cls_set in videos[class_col]
    ])
    video_ids = videos[video_col].values

    test_size = round(1.0 - train, 4)
    msss = MultilabelStratifiedShuffleSplit(
        n_splits=1, test_size=test_size, random_state=seed
    )
    train_idx, valtest_idx = next(msss.split(video_ids, presence))

    val_ratio = val / (1.0 - train)
    msss2 = MultilabelStratifiedShuffleSplit(
        n_splits=1, test_size=round(1.0 - val_ratio, 4), random_state=seed
    )
    val_idx, test_idx = next(
        msss2.split(video_ids[valtest_idx], presence[valtest_idx])
    )

    return (
        set(video_ids[train_idx]),
        set(video_ids[valtest_idx][val_idx]),
        set(video_ids[valtest_idx][test_idx]),
    )
